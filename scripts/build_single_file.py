"""Embed runtime support modules into app_v84_hermes.py for single-file deployment.

The sibling module files remain the source of truth. Running this script refreshes
an embedded-source block in app_v84_hermes.py and writes an optional copy to
`dist/app_v84_hermes_single.py`.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'app_v84_hermes.py'
MODULES = [
    'blade_deepseek_pipeline',
    'blade_ml_engine',
    'okooo_mobile_cs',
    'odds_index_math',
    'odds_fallback',
    'sporttery_jc',
    'convergence_arbitrator',
    'ProductionRunnerBridge',
    'blade_monitor_panel',
]
START = '# >>> FLANALYZER_EMBEDDED_RUNTIME_MODULES >>>'
END = '# <<< FLANALYZER_EMBEDDED_RUNTIME_MODULES <<<'
KB_DIR = ROOT / 'knowledge_base'
KB_FILES = ['statistical_skills.json', 'strategy_skills.json']
SEED_START = '# >>> FLANALYZER_EMBEDDED_KNOWLEDGE_BASE >>>'
SEED_END = '# <<< FLANALYZER_EMBEDDED_KNOWLEDGE_BASE <<<'


def knowledge_base_skills() -> dict[str, list[dict]]:
    """Read the canonical knowledge_base JSON files that ship in the repository."""
    out: dict[str, list[dict]] = {}
    for name in KB_FILES:
        path = KB_DIR / name
        if not path.exists():
            raise RuntimeError(f'knowledge base seed missing: {path}')
        data = json.loads(path.read_text(encoding='utf-8'))
        skills = data.get('skills') if isinstance(data, dict) else None
        if not isinstance(skills, list) or not skills:
            raise RuntimeError(f'knowledge base seed is empty: {path}')
        out[name] = skills
    return out


def build_seed_block() -> str:
    """Emit the `_SEED_SKILLS` class attribute body for SkillMatchingEngine."""
    seeds = knowledge_base_skills()
    payload = json.dumps(seeds, ensure_ascii=False, indent=4)
    # indent under the class body (4 spaces) and keep it a single statement.
    payload = payload.replace('\n', '\n    ')
    return (
        f'{SEED_START}\n'
        f'    # Generated from knowledge_base/*.json by scripts/build_single_file.py. Do not hand-edit.\n'
        f'    _SEED_SKILLS: ClassVar[dict[str, list[dict[str, Any]]]] = {payload}\n'
        f'{SEED_END}'
    )


def refresh_seed_block(text: str) -> str:
    """Replace (or insert) the embedded knowledge-base seed inside SkillMatchingEngine."""
    block = build_seed_block()
    if SEED_START in text and SEED_END in text:
        before = text.split(SEED_START, 1)[0]
        after = text.split(SEED_END, 1)[1]
        return before + block + after
    # 未带 sentinel 的旧文件：整段 `_SEED_SKILLS: ClassVar[...] = <literal>` 替换掉。
    pattern = re.compile(
        r'^[ \t]*_SEED_SKILLS: ClassVar\[dict\[str, list\[dict\[str, Any\]\]\]\] = \{[\s\S]*?\n(?=[ \t]*\n|class |[ \t]*@)',
        re.MULTILINE,
    )
    match = pattern.search(text)
    if not match:
        raise RuntimeError('SkillMatchingEngine._SEED_SKILLS anchor not found')
    return text[:match.start()] + block + '\n' + text[match.end():]


def build_block() -> str:
    sources = {name: (ROOT / f'{name}.py').read_text(encoding='utf-8') for name in MODULES}
    payload = json.dumps(sources, ensure_ascii=False, indent=2)
    module_list = ', '.join(repr(name) for name in MODULES)
    return f'''{START}
# Generated by scripts/build_single_file.py. Do not hand-edit this block.
def _flanalyzer_install_embedded_runtime_modules():
    """Install embedded runtime modules when sibling .py files are absent."""
    import importlib.util as _fl_embed_importlib_util
    import sys as _fl_embed_sys
    import types as _fl_embed_types

    _sources = {payload}
    for _name in ({module_list},):
        if _name in _fl_embed_sys.modules:
            continue
        try:
            if _fl_embed_importlib_util.find_spec(_name) is not None:
                continue
        except (ImportError, ValueError, AttributeError):
            pass
        _src = _sources.get(_name)
        if not _src:
            continue
        _mod = _fl_embed_types.ModuleType(_name)
        _filename = f"<embedded:{{_name}}>"
        _mod.__file__ = _filename
        _mod.__package__ = ''
        _fl_embed_sys.modules[_name] = _mod
        # The embedded payload is generated from trusted repository module files.
        exec(compile(_src, _filename, 'exec'), _mod.__dict__)  # noqa: S102  # nosec B102


_flanalyzer_install_embedded_runtime_modules()
{END}'''


def refresh_app() -> str:
    text = APP.read_text(encoding='utf-8')
    block = build_block()
    if START in text and END in text:
        before = text.split(START, 1)[0]
        after = text.split(END, 1)[1]
        text = before + block + after
    else:
        anchor = 'from typing import Any, ClassVar, cast, overload\n'
        if anchor not in text:
            raise RuntimeError('typing import anchor not found')
        text = text.replace(anchor, anchor + '\n' + block + '\n', 1)
    text = refresh_seed_block(text)
    APP.write_text(text, encoding='utf-8')
    return text


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', default='dist/app_v84_hermes_single.py')
    args = parser.parse_args()
    text = refresh_app()
    out = ROOT / args.output
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    print(out)


if __name__ == '__main__':
    main()
