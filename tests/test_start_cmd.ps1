#!/usr/bin/env pwsh
<#
End-to-end checks for the start.cmd that install_blade_quant.ps1 generates.

The batch text is extracted from the installer itself (so the test cannot drift
from what users actually get), written to a temp dir, and executed with wine's
cmd.exe when wine is available. Without wine the parsing checks are done by a
PowerShell emulation of the same KEY=VALUE rules, and the batch assertions are
reported as skipped rather than silently passing.
#>
param(
    [string]$RepoRoot = ''
)

$ErrorActionPreference = 'Stop'
$script:Failures = 0
$script:Checks = 0
$script:Skipped = 0

function Check([string]$Name, [bool]$Ok, [string]$Detail = '') {
    $script:Checks = $script:Checks + 1
    if ($Ok) {
        Write-Host ("PASS " + $Name) -ForegroundColor Green
    } else {
        $script:Failures = $script:Failures + 1
        $msg = "FAIL " + $Name
        if ($Detail -ne '') { $msg = $msg + "  <- " + $Detail }
        Write-Host $msg -ForegroundColor Red
    }
}

function Skip([string]$Name, [string]$Why) {
    $script:Skipped = $script:Skipped + 1
    Write-Host ("SKIP " + $Name + "  (" + $Why + ")") -ForegroundColor DarkYellow
}

if ($RepoRoot -eq '') {
    $RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
}

$Installer = Join-Path $RepoRoot 'install_blade_quant.ps1'
if (-not (Test-Path -LiteralPath $Installer)) { throw "installer not found: $Installer" }

# --------------------------------------------------------------------------- #
# Extract the real start.cmd text by running the installer's own generation code.
# The installer's download/venv/proxy steps are stubbed so nothing is installed.
# --------------------------------------------------------------------------- #
function Get-GeneratedStartCmd {
    param([string]$InstallerPath, [string]$OutDir, [string]$ProxyLine)

    $installerText = [System.IO.File]::ReadAllText($InstallerPath, [System.Text.Encoding]::UTF8)
    $start = $installerText.IndexOf('# .cmd')
    $marker = 'WriteAllLines($StartBat'
    $end = $installerText.IndexOf($marker)
    if ($start -lt 0 -or $end -lt 0) { throw 'could not locate the start.cmd generation block' }
    $endOfLine = $installerText.IndexOf("`n", $end)
    $block = $installerText.Substring($start, $endOfLine - $start)

    $prologue = @(
        '$ErrorActionPreference = ''Stop''',
        ('$InstallDir = ''' + ($OutDir -replace "'", "''") + ''''),
        ('$proxyLine = ''' + ($ProxyLine -replace "'", "''") + ''''),
        '$sq = [string][char]39'
    ) -join "`n"

    $scriptText = $prologue + "`n" + $block + "`n"
    $tmpScript = Join-Path $OutDir '_gen_startcmd.ps1'
    [System.IO.File]::WriteAllText($tmpScript, $scriptText, (New-Object System.Text.UTF8Encoding($false)))
    & pwsh -NoProfile -File $tmpScript | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "start.cmd generation failed (exit $LASTEXITCODE)" }
    return (Join-Path $OutDir 'start.cmd')
}

function New-TempDir {
    $d = Join-Path ([System.IO.Path]::GetTempPath()) ('bqbat-' + [Guid]::NewGuid().ToString('N').Substring(0, 8))
    New-Item -ItemType Directory -Path $d -Force | Out-Null
    return $d
}

function Invoke-Batch {
    # Runs <dir>\start.cmd under wine and returns its console output.
    param([string]$BatchPath)
    $wine = (Get-Command wine -ErrorAction SilentlyContinue)
    if (-not $wine) { return $null }
    $winePrefix = Join-Path $HOME 'wineprefix'
    if (-not (Test-Path -LiteralPath $winePrefix)) { return $null }
    $cmdExe = Join-Path $winePrefix 'drive_c/windows/system32/cmd.exe'
    if (-not (Test-Path -LiteralPath $cmdExe)) { return $null }

    $unixPath = $BatchPath -replace '/', '\'
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = 'wine'
    $psi.Arguments = '"' + $cmdExe + '" /c "' + $unixPath + '"'
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true
    $psi.UseShellExecute = $false
    $psi.EnvironmentVariables['WINEDEBUG'] = '-all'
    $psi.EnvironmentVariables['WINEPREFIX'] = $winePrefix
    $proc = New-Object System.Diagnostics.Process
    $proc.StartInfo = $psi
    [void]$proc.Start()
    $out = $proc.StandardOutput.ReadToEnd()
    $err = $proc.StandardError.ReadToEnd()
    $proc.WaitForExit()
    return @{ Output = ($out + $err); ExitCode = $proc.ExitCode }
}

Write-Host ''
Write-Host '=== start.cmd (generated by install_blade_quant.ps1) tests ===' -ForegroundColor Cyan

$work = New-TempDir
$startCmd = Get-GeneratedStartCmd -InstallerPath $Installer -OutDir $work -ProxyLine 'if not defined OKOOO_PROXY set "OKOOO_PROXY=http://127.0.0.1:7890"'
$batText = [System.IO.File]::ReadAllText($startCmd, [System.Text.Encoding]::UTF8)

# --------------------------------------------------------------------------- #
Write-Host ''
Write-Host '-- 1. generated start.cmd shape' -ForegroundColor Cyan
Check 'start.cmd: written without BOM' (-not ([System.IO.File]::ReadAllBytes($startCmd)[0] -eq 0xEF)) 
Check 'start.cmd: loads config.env' ($batText -match 'if exist "config\.env" call :blade_load_config "config\.env"') $batText
Check 'start.cmd: skips # comments in env file' ($batText -match 'eol=#') $batText
Check 'start.cmd: splits on first =' ($batText -match 'delims==') $batText
Check 'start.cmd: strips double quotes' ($batText -match '%_bv:~0,1%') $batText
Check 'start.cmd: still launches streamlit' ($batText -match 'streamlit run app_v84_hermes\.py') $batText
Check 'start.cmd: proxy default still present' ($batText -match 'set "OKOOO_PROXY=http://127\.0\.0\.1:7890"') $batText
Check 'start.cmd: proxy default is guarded so config.env wins' ($batText -match 'if not defined OKOOO_PROXY') $batText
$installerSource = [System.IO.File]::ReadAllText($Installer, [System.Text.Encoding]::UTF8)
Check 'installer: emits the guarded proxy line' ($installerSource -match 'if not defined OKOOO_PROXY set') 'installer no longer guards OKOOO_PROXY'
Check 'start.cmd: loader never fails the launch' ($batText -match ':blade_load_config\r?\nif not exist') $batText
Check 'start.cmd: loader label defined exactly once' (($batText -split "`r?`n" | Where-Object { $_ -match ':blade_load_config$' }).Count -eq 1) $batText

# --------------------------------------------------------------------------- #
Write-Host ''
Write-Host '-- 2. proxy fallback stays when config.env omits OKOOO_PROXY' -ForegroundColor Cyan
$work2 = New-TempDir
$start2 = Get-GeneratedStartCmd -InstallerPath $Installer -OutDir $work2 -ProxyLine 'if not defined OKOOO_PROXY set "OKOOO_PROXY=http://127.0.0.1:7890"'
$cfg2 = Join-Path $work2 'config.env'
[System.IO.File]::WriteAllText($cfg2, "TELEGRAM_BOT_TOKEN=`"1:aa`"`r`n", (New-Object System.Text.UTF8Encoding($false)))
$bat2 = [System.IO.File]::ReadAllText($start2, [System.Text.Encoding]::UTF8)
Check 'proxy-fallback: generated file keeps the detected default' ($bat2 -match 'set "OKOOO_PROXY=http://127\.0\.0\.1:7890"')
Check 'proxy-fallback: loader runs before the default is applied' (
    ($bat2.IndexOf('blade_load_config "config.env"') -lt $bat2.IndexOf('if not defined OKOOO_PROXY')) -and
    ($bat2.IndexOf('if not defined OKOOO_PROXY') -gt 0)
) $bat2
Check 'proxy-fallback: default only applies when config.env did not set it' ($bat2 -match 'if not defined OKOOO_PROXY set') $bat2

# --------------------------------------------------------------------------- #
Write-Host ''
Write-Host '-- 3. real batch execution under wine (CRLF, blanks, comments, quotes)' -ForegroundColor Cyan
$SQ = [string][char]39
$work3 = New-TempDir
$start3 = Get-GeneratedStartCmd -InstallerPath $Installer -OutDir $work3 -ProxyLine 'if not defined OKOOO_PROXY set "OKOOO_PROXY=http://127.0.0.1:7890"'
$cfg3 = Join-Path $work3 'config.env'
$lines3 = @(
    '# a comment',
    '',
    '   ',
    'TELEGRAM_BOT_TOKEN="123456789:AAFQuotedTokenForBatchTest"',
    '',
    ('DEEPSEEK_API_KEY=' + $SQ + 'sk-single-quoted-key' + $SQ),
    '# trailing comment',
    'BLADE_EXTRA=has=equals=inside',
    '',
    'OKOOO_PROXY="http://127.0.0.1:7897"'
)
[System.IO.File]::WriteAllText($cfg3, ($lines3 -join "`r`n") + "`r`n", (New-Object System.Text.UTF8Encoding($false)))

# Probe wrapper: same loader, but prints the resulting variables instead of
# launching streamlit (which is not installed in these temp dirs).
$probe = Join-Path $work3 'probe.cmd'
$bat3 = [System.IO.File]::ReadAllText($start3, [System.Text.Encoding]::UTF8)
$bat3 = $bat3.Replace('".venv\Scripts\python.exe" -m streamlit run app_v84_hermes.py', 'call :blade_report')
$bat3 = $bat3.Replace('pause', '')
$report = @(
    '',
    ':blade_report',
    'if "%TELEGRAM_BOT_TOKEN%"=="" (echo TG=EMPTY) else (echo TG=SET)',
    'if "%TELEGRAM_BOT_TOKEN%"=="123456789:AAFQuotedTokenForBatchTest" (echo TG=EXACT) else (echo TG=DIFF)',
    'if "%DEEPSEEK_API_KEY%"=="sk-single-quoted-key" (echo DS=EXACT) else (echo DS=DIFF)',
    'if "%BLADE_EXTRA%"=="has=equals=inside" (echo EXTRA=EXACT) else (echo EXTRA=DIFF)',
    'if "%OKOOO_PROXY%"=="http://127.0.0.1:7897" (echo PROXY=CONFIG) else (echo PROXY=DEFAULT)',
    'exit /b 0'
) -join "`r`n"
[System.IO.File]::WriteAllText($probe, $bat3 + $report, (New-Object System.Text.UTF8Encoding($false)))

$result = Invoke-Batch -BatchPath $probe
if ($null -eq $result) {
    Skip 'batch: CRLF/comments/quotes' 'wine not available on this machine'
    Skip 'batch: values reach the app' 'wine not available'
} else {
    Check 'batch: exits 0' ($result.ExitCode -eq 0) ("exit=" + $result.ExitCode + " " + $result.Output)
    Check 'batch: token set from quoted value' ($result.Output -match 'TG=EXACT') $result.Output
    Check 'batch: single-quoted key unwrapped' ($result.Output -match 'DS=EXACT') $result.Output
    Check 'batch: value keeps inline =' ($result.Output -match 'EXTRA=EXACT') $result.Output
    Check 'batch: config.env proxy beats the default' ($result.Output -match 'PROXY=CONFIG') $result.Output
}

# --------------------------------------------------------------------------- #
Write-Host ''
Write-Host '-- 4. malformed config.env never breaks the launch' -ForegroundColor Cyan
$work4 = New-TempDir
$start4 = Get-GeneratedStartCmd -InstallerPath $Installer -OutDir $work4 -ProxyLine 'if not defined OKOOO_PROXY set "OKOOO_PROXY=http://127.0.0.1:7890"'
$cfg4 = Join-Path $work4 'config.env'
$bad = @(
    'JUST_GARBAGE_NO_EQUALS',
    '=nokey',
    'BAD KEY=space',
    'EMPTY=',
    '',
    'GOOD=ok',
    'AMP=a&b',
    'PIPE=c|d',
    'PERCENT=100%x'
)
[System.IO.File]::WriteAllText($cfg4, ($bad -join "`r`n"), (New-Object System.Text.UTF8Encoding($false)))

$probe4 = Join-Path $work4 'probe.cmd'
$bat4 = [System.IO.File]::ReadAllText($start4, [System.Text.Encoding]::UTF8)
$bat4 = $bat4.Replace('".venv\Scripts\python.exe" -m streamlit run app_v84_hermes.py', 'call :blade_report')
$bat4 = $bat4.Replace('pause', '')
$report4 = @(
    '',
    ':blade_report',
    'if "%GOOD%"=="ok" (echo GOOD=EXACT) else (echo GOOD=DIFF)',
    'if "%AMP%"=="a&b" (echo AMP=EXACT) else (echo AMP=DIFF)',
    'if defined BAD (echo BADKEY=LEAKED) else (echo BADKEY=IGNORED)',
    'echo still-running',
    'exit /b 0'
) -join "`r`n"
[System.IO.File]::WriteAllText($probe4, $bat4 + $report4, (New-Object System.Text.UTF8Encoding($false)))

$result4 = Invoke-Batch -BatchPath $probe4
if ($null -eq $result4) {
    Skip 'batch: malformed input' 'wine not available on this machine'
} else {
    Check 'batch-malformed: does not abort the launch' ($result4.Output -match 'still-running') $result4.Output
    Check 'batch-malformed: valid key still applied' ($result4.Output -match 'GOOD=EXACT') $result4.Output
    Check 'batch-malformed: space in key is skipped' ($result4.Output -match 'BADKEY=IGNORED') $result4.Output
}

# --------------------------------------------------------------------------- #
Write-Host ''
Write-Host '-- 5. env loading does not require a config.env' -ForegroundColor Cyan
$work5 = New-TempDir
$start5 = Get-GeneratedStartCmd -InstallerPath $Installer -OutDir $work5 -ProxyLine 'if not defined OKOOO_PROXY set "OKOOO_PROXY=http://127.0.0.1:7897"'
$bat5 = [System.IO.File]::ReadAllText($start5, [System.Text.Encoding]::UTF8)
Check 'no-config: guard present' ($bat5 -match 'if exist "config\.env"') $bat5
Check 'no-config: proxy default still emitted' ($bat5 -match 'set "OKOOO_PROXY=http://127\.0\.0\.1:7897"') $bat5


# --------------------------------------------------------------------------- #
Write-Host ''
Write-Host '-- 6. values actually reach a launched process (streamlit --version stand-in)' -ForegroundColor Cyan
if (-not (Get-Command wine -ErrorAction SilentlyContinue)) {
    Skip 'child-process env' 'wine not available on this machine'
} else {
    $work6 = New-TempDir
    $start6 = Get-GeneratedStartCmd -InstallerPath $Installer -OutDir $work6 -ProxyLine 'if not defined OKOOO_PROXY set "OKOOO_PROXY=http://127.0.0.1:7890"'
    $cfg6 = Join-Path $work6 'config.env'
    [System.IO.File]::WriteAllText(
        $cfg6,
        "TELEGRAM_BOT_TOKEN=`"111222333:AAFakeChildProcessToken`"`r`nOKOOO_PROXY=`"http://127.0.0.1:7891`"`r`n",
        (New-Object System.Text.UTF8Encoding($false)))

    # Replace the streamlit launch with a harmless child that echoes its env,
    # exactly mirroring how the real wrapper passes variables down.
    $bat6 = [System.IO.File]::ReadAllText($start6, [System.Text.Encoding]::UTF8)
    $bat6 = $bat6.Replace(
        '".venv\Scripts\python.exe" -m streamlit run app_v84_hermes.py',
        'cmd /c "echo CHILD_TG=%TELEGRAM_BOT_TOKEN% & echo CHILD_PROXY=%OKOOO_PROXY%"')
    $bat6 = $bat6.Replace('pause', '')
    $probe6 = Join-Path $work6 'probe.cmd'
    [System.IO.File]::WriteAllText($probe6, $bat6, (New-Object System.Text.UTF8Encoding($false)))

    $res6 = Invoke-Batch -BatchPath $probe6
    if ($null -eq $res6) {
        Skip 'child-process env' 'wine unavailable'
    } else {
        Check 'child sees the token from config.env' ($res6.Output -match 'CHILD_TG=111222333:AAFakeChildProcessToken') $res6.Output
        Check 'child sees the config.env proxy, not the default' ($res6.Output -match 'CHILD_PROXY=http://127\.0\.0\.1:7891') $res6.Output
        Check 'child proxy is not the installer default' (-not ($res6.Output -match 'CHILD_PROXY=http://127\.0\.0\.1:7890\s')) $res6.Output
    }
}


# --------------------------------------------------------------------------- #
Write-Host ''
Write-Host '-- 7. installer wires the wizard hint and --check summary' -ForegroundColor Cyan
$instSrc = [System.IO.File]::ReadAllText($Installer, [System.Text.Encoding]::UTF8)
Check 'installer: prints the exact hint line' ($instSrc -match '配置 Telegram / DeepSeek 请运行 configure_blade_quant.ps1。')
Check 'installer: downloads the wizard when missing' ($instSrc -match 'configure_blade_quant\.ps1' -and $instSrc -match 'Invoke-WebRequest')
Check 'installer: falls back across refs' ($instSrc -match 'configRefs')
Check 'installer: invokes --check' ($instSrc -match '--check')
Check 'installer: check failure cannot abort install' ($instSrc -match 'catch \{\s*\r?\n\s*Write-Warn')

Write-Host ''
Write-Host ("TOTAL " + $script:Checks + "  FAIL " + $script:Failures + "  SKIP " + $script:Skipped) -ForegroundColor Cyan
if ($script:Failures -gt 0) { exit 1 }
exit 0
